"""Write COMPONENTS.md: a per-file manifest of what the published RX3 Mod is built from.

For every module that can end up in a published template it lists each packaged file and each build input with its size, SHA-256, the SPDX licence
declared in the file's own header (or "none declared"), the module that owns it and, for artwork, the script that generated it. The compiled core
(librx3_core.so) is listed as the output of the listed build inputs. Run from the repository root:

    python scripts/build_components_manifest.py
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
MODULES = ROOT / "mod" / "modules"
# modules that appear in at least one published template (see scripts/build_template.py)
PUBLISHED = ["core", "compatibility", "logging", "logo", "samples", "stems", "theme-white"]
GENERATED = {
    "glyph-atlas-dark.rgb565": "mod/modules/core/build_labels.py --font Inter.ttf --font-size 21 --theme dark",
    "glyph-atlas-light.rgb565": "mod/modules/core/build_labels.py --font Inter.ttf --font-size 21 --theme light",
}
SPDX = re.compile(r"SPDX-License-Identifier:\s*([A-Za-z0-9.\-+ ()]+)")


def licence(path: pathlib.Path) -> str:
    if path.suffix in {".rgb565", ".bin"}:
        return "generated artwork (see ASSETS.md)"
    try:
        head = "\n".join(path.read_text(encoding="utf-8", errors="replace").splitlines()[:12])
    except OSError:
        return "unreadable"
    found = SPDX.search(head)
    return found.group(1).strip() if found else "none declared in file"


def row(owner: str, relative: str, role: str) -> str | None:
    path = MODULES / owner / relative
    if not path.is_file():
        return f"| `{owner}` | `{relative}` | {role} | missing | | | |"
    digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    how = GENERATED.get(path.name) or ("mod/modules/core/build_tabs.py --font Inter.ttf" if path.suffix == ".rgb565" and "logo" not in path.name else "")
    return f"| `{owner}` | `{relative}` | {role} | {path.stat().st_size} | `{digest}` | {licence(path)} | {how} |"


def main() -> int:
    try:
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        commit = "(not a git checkout)"
    lines = [
        "<!-- SPDX-License-Identifier: MPL-2.0 -->",
        "# Component manifest",
        "",
        "Per-file list of what the published RX3 Mod is built from, generated by `scripts/build_components_manifest.py`. Regenerate it with every release.",
        f"Source commit when generated: `{commit}` (the commit that adds this file is the next one).",
        "",
        "- **Base:** `rx3-toolkit` by Tratosca (MPL-2.0), copied 2026-10-12. Files we changed are listed in `ZADRY_CHANGES.md`. Files without an SPDX header are listed as such; do not assume a licence for them.",
        "- **Shipped** = copied into the template (runs on the deck); **build input** = compiled into `librx3_core.so` (the only compiled binary in the template) or used to build it.",
        "- Nothing here is, or is derived from, a firmware image, a binary or an image authored by the player's manufacturer, and no key is stored in this repository (see `LEGAL.md`).",
        "- Typeface used only to rasterise artwork: Inter (SIL OFL 1.1), licence in `mod/modules/core/OFL-Inter.txt`; the font file is not distributed.",
        "",
        "| Module | File | Role | Bytes | SHA-256 (16) | Licence declared | Generated by |",
        "| --- | --- | --- | ---: | --- | --- | --- |",
    ]
    for module in PUBLISHED:
        manifest_path = MODULES / module / "manifest.json"
        if not manifest_path.is_file():
            continue
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        seen: set[str] = set()
        for entry in manifest.get("files", []):
            source = entry["source"]
            if source not in seen:
                seen.add(source)
                lines.append(row(module, source, "shipped"))
        for source in manifest.get("build_files", []):
            if source not in seen:
                seen.add(source)
                lines.append(row(module, source, "build input"))
        hook = manifest.get("arm_hook")
        if hook and hook.get("source") and hook["source"] not in seen:
            lines.append(row(module, hook["source"], "build input (ARM hook)"))
    lines += [
        "",
        "`mod/lib/*.sh`, `mod/autoexec.sh` and `mod/compatibility.sh` are the shell entry points shipped in every template; they carry their own SPDX headers.",
        "The user's logo, when present, is user-supplied artwork written at build time and is not part of this manifest.",
    ]
    (ROOT / "COMPONENTS.md").write_text("\n".join(x for x in lines if x is not None) + "\n", encoding="utf-8")
    print(f"COMPONENTS.md written ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
